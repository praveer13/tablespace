/// left_deep_dp: a 4-table chain 0–1–2–3. The selective edge (2⋈3 at
/// 10 ppm, with an index on table 3's side and on table 2's col 1) sits at
/// the END of id order: joining left-to-right builds a 320,000-row
/// intermediate at the first step and a 3,200,000-row one at the second.
/// The DP starts at the selective edge and never sees five figures.
fn card_chain4() -> StatsCard {
    StatsCard {
        tables: vec![
            TableStat { rows: 20_000, pages: 1_000 },
            TableStat { rows: 8_000, pages: 400 },
            TableStat { rows: 100_000, pages: 5_000 },
            TableStat { rows: 300, pages: 15 },
        ],
        edges: vec![
            Edge { a: 0, b: 1, col_a: 0, col_b: 0, sel_ppm: 2_000, index_a: false, index_b: false },
            Edge { a: 1, b: 2, col_a: 0, col_b: 0, sel_ppm: 100, index_a: false, index_b: false },
            Edge { a: 2, b: 3, col_a: 1, col_b: 0, sel_ppm: 10, index_a: true, index_b: true },
        ],
    }
}

/// interesting_orders: a 3-table chain 0–1–2 where EVERY join is on
/// column 0 — so a merge join's output order serves the next merge
/// directly. {0,1} by hash is the cheapest pair plan, but the pair merge
/// (2nd cheapest) arrives sorted on (1, col 0), which makes the top merge
/// with table 2 free of any outer sort — and table 2's index feeds the
/// merge's inner side sorted. Cheapest-per-subset pruning loses.
fn card_interesting() -> StatsCard {
    StatsCard {
        tables: vec![
            TableStat { rows: 300_000, pages: 15_000 },
            TableStat { rows: 30_000, pages: 1_500 },
            TableStat { rows: 20_000, pages: 1_000 },
        ],
        edges: vec![
            Edge { a: 0, b: 1, col_a: 0, col_b: 0, sel_ppm: 50, index_a: true, index_b: true },
            Edge { a: 1, b: 2, col_a: 0, col_b: 0, sel_ppm: 2_000, index_a: true, index_b: true },
        ],
    }
}

/* --------------------------- CALIBRATION ----------------------------
 * Reference solution (labs/_solutions/optimizer), these pins, native
 * x86-64, 2026-08 — with a brute-force cross-check that enumerates EVERY
 * valid plan (connected order × method × legal scan) for the scripted
 * cards and prices it with the harness walker:
 *
 *   left_deep_dp: optimum 7,812,800 milliunits via [3,2,1,0] with
 *     (NestLoop,Hash,Hash) — the ONLY plan at that cost out of 792 valid
 *     plans. Naive [0,1,2,3] = 90,381,000 — 11.57× worse.
 *   interesting_orders: optimum 81,500,000 via (Merge,Merge) — exactly two
 *     plans reach it, orders [0,1,2] and [1,0,2], both with all-index
 *     scans; no other method mix comes close. Cheapest-per-subset-only
 *     (and the naive order) = 117,000,000 — 1.436× worse.
 *   beats_naive: 67 stars in the seeded 200; reference naive/dp ratio
 *     min 2.000×, mean 2.453×. STAR_FACTOR_MILLI = 1200 (1.20×) is 60% of
 *     the measured minimum — headroom for legitimate variation.
 *   storm: max reference cost over the 100 cards ≈ 6.4×10¹³ milliunits —
 *     nowhere near the u64 clamp, so every card grades real arithmetic.
 */

/// beats_naive: required worst-case naive/dp ratio over the seeded star
/// graphs, in milli-ratio (1200 = 1.20×). Measured reference minimum over
/// the 67 seeded stars: 2.000× — the constant is 60% of that (CALIBRATION).
const STAR_FACTOR_MILLI: u64 = 1_200;

