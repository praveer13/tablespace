//! optimizer — forge lab 08 (tablespace).
//!
//! The planner you blamed in T5 is, underneath, one beautiful algorithm:
//! Selinger's dynamic program. The harness is the statistics sketch (exact
//! here — no estimation error to hide behind); the student writes the
//! search: System R's left-deep enumeration over join subsets, priced in
//! fixed-point milliunits, keeping cheapest plans per (subset, interesting
//! order). Graded on exact arithmetic against a reference optimizer over
//! seeded random query graphs.
//!
//! ┌────────────────────────────────────────────────────────────────┐
//! │  YOU EDIT:   src/planner.rs     (the only file with TODO(you)) │
//! │  DO NOT EDIT this file — it is the grading harness.            │
//! └────────────────────────────────────────────────────────────────┘
//!
//! The five checks, in grading order:
//!   * cost_model         — the student's cost_of against hand-computed
//!                          milliunit answers on three scripted scenarios.
//!   * left_deep_dp       — a 4-table chain where the naive id-order is
//!                          provably wrong; exact optimum + order + methods.
//!   * interesting_orders — a scenario where the 2nd-cheapest pair join's
//!                          sorted output makes the top merge free.
//!   * beats_naive        — 200 seeded graphs: never worse than naive;
//!                          star graphs must win by a calibrated factor.
//!   * storm              — 100 seeded graphs: cost EXACTLY the reference
//!                          DP's optimum, plan structurally valid, and the
//!                          reported total_cost honest to the bit.

