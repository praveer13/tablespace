/// 1. cost_model: three hand-built scenarios, five plans, answers known to
///    the milliunit by hand — the student's cost_of must reproduce the
///    pinned arithmetic before any search may be graded.
pub fn check_cost_model() -> Check {
    const ID: &str = "cost_model";
    const LABEL: &str = "cost arithmetic matches the harness model exactly";

    // scenario 1: an in-memory hash join, priced end to end
    let card1 = StatsCard {
        tables: vec![
            TableStat { rows: 2_000, pages: 100 },
            TableStat { rows: 8_000, pages: 400 },
        ],
        edges: vec![Edge { a: 0, b: 1, col_a: 0, col_b: 0, sel_ppm: 500, index_a: false, index_b: false }],
    };
    let p1 = Plan {
        join_order: vec![0, 1],
        methods: vec![JoinMethod::Hash],
        scans: vec![ScanMethod::Seq, ScanMethod::Seq],
        total_cost: 700.0,
    };
    // scenario 2: the OLTP probe vs the Grace spill
    let card2 = StatsCard {
        tables: vec![
            TableStat { rows: 300, pages: 15 },
            TableStat { rows: 200_000, pages: 10_000 },
        ],
        edges: vec![Edge { a: 0, b: 1, col_a: 0, col_b: 0, sel_ppm: 5, index_a: false, index_b: true }],
    };
    let p2a = Plan {
        join_order: vec![0, 1],
        methods: vec![JoinMethod::NestLoop],
        scans: vec![ScanMethod::Seq, ScanMethod::Index(0)],
        total_cost: 3_621.0,
    };
    let p2b = Plan {
        join_order: vec![0, 1],
        methods: vec![JoinMethod::Hash],
        scans: vec![ScanMethod::Seq, ScanMethod::Seq],
        total_cost: 36_054.0,
    };
    // scenario 3: a merge join that buys one sort, vs the cheap hash
    let card3 = StatsCard {
        tables: vec![
            TableStat { rows: 50_000, pages: 2_500 },
            TableStat { rows: 4_000, pages: 200 },
        ],
        edges: vec![Edge { a: 0, b: 1, col_a: 0, col_b: 0, sel_ppm: 100, index_a: true, index_b: false }],
    };
    let p3a = Plan {
        join_order: vec![0, 1],
        methods: vec![JoinMethod::Merge],
        scans: vec![ScanMethod::Index(0), ScanMethod::Seq],
        total_cost: 11_760.0,
    };
    let p3b = Plan {
        join_order: vec![0, 1],
        methods: vec![JoinMethod::Hash],
        scans: vec![ScanMethod::Seq, ScanMethod::Seq],
        total_cost: 3_780.0,
    };

    let scenarios: Vec<(&str, StatsCard, Vec<(Plan, u64, &str)>)> = vec![
        (
            "in-memory hash join",
            card1,
            vec![(
                p1,
                700_000,
                "scan A = 100·1000 + 2,000·10 = 120,000; hash adds scan B (400·1000 + 8,000·10) = 480,000 + cpu (2,000+8,000)·10 = 100,000; the 8,000-row build is 3.2 MB ≤ work_mem — no spill",
            )],
        ),
        (
            "indexed nested-loop vs Grace hash",
            card2,
            vec![
                (
                    p2a,
                    3_621_000,
                    "scan C = 15·1000 + 300·10 = 18,000; then 300 probes × (3·4000 + 10) = 3,603,000 — INDEX_PROBE_PAGES random pages per outer row",
                ),
                (
                    p2b,
                    36_054_000,
                    "scan C 18,000 + scan D (10,000·1000 + 200,000·10) 12,000,000 + cpu 2,003,000; the 200,000-row build is 80 MB > work_mem → Grace: + 2·(15+10,000)·1000 = 20,030,000 spill I/O + another 2,003,000 cpu",
                ),
            ],
        ),
        (
            "merge join buying one sort",
            card3,
            vec![
                (
                    p3a,
                    11_760_000,
                    "outer arrives sorted via the index scan (2,500·4000 + 50,000·10) = 10,500,000; inner seq 240,000 + sort(4,000) = 4,000·12·10 = 480,000 (fits work_mem); merge walk (50,000+4,000)·10 = 540,000",
                ),
                (
                    p3b,
                    3_780_000,
                    "seq E (2,500·1000 + 50,000·10) 3,000,000 + seq F 240,000 + cpu 540,000; build fits — the hash wins here and the model must SAY so",
                ),
            ],
        ),
    ];

    for (name, card, plans) in &scenarios {
        for (p, want, walk) in plans {
            let got = cost_of(p, card);
            if got != *want {
                return Check::fail(
                    ID,
                    LABEL,
                    format!(
                        "scenario \"{name}\": cost_of returned {got} milliunits, the pinned arithmetic says {want} — {walk}"
                    ),
                );
            }
        }
    }
    Check::pass(
        ID,
        LABEL,
        "5 plans across 3 scenarios priced to the milliunit — seq/index scans, indexed probes, the Grace spill, a bought sort",
    )
}

/// 2. left_deep_dp: the 4-table chain where the naive id-order is provably
///    wrong — exact optimum cost, order, and methods.
pub fn check_left_deep_dp() -> Check {
    const ID: &str = "left_deep_dp";
    const LABEL: &str = "cheapest left-deep plan on a 4-table chain";
    let card = card_chain4();
    let best = ref_dp(&card, true);
    let (naive, naive_cost) = naive_plan(&card);
    if naive_cost < best.cost * 4 {
        return Check::fail(
            ID,
            LABEL,
            format!("harness calibration bug: the scripted chain barely punishes naive ({naive_cost} vs {})", best.cost),
        );
    }
    let got = plan(&card);
    if let Err(e) = validate(&card, &got) {
        return Check::fail(ID, LABEL, format!("invalid plan: {e}"));
    }
    let got_cost = cost_walk(&card, &got);
    if got_cost != best.cost {
        return Check::fail(
            ID,
            LABEL,
            format!(
                "your plan costs {got_cost} milliunits; the DP optimum is {} via {:?} with {:?} — the naive {:?} pays {} because it builds a 320,000-row intermediate at step 1 while the selective edge (2⋈3, 10 ppm) waits its turn. Optimal substructure: price every SUBSET, don't walk left to right",
                best.cost, best.order, best.methods, naive.join_order, naive_cost
            ),
        );
    }
    if got.join_order != best.order || got.methods != best.methods {
        return Check::fail(
            ID,
            LABEL,
            format!(
                "right cost, wrong plan: the unique optimum is {:?} with {:?}, you returned {:?} with {:?} (uniqueness brute-forced over every connected order × method × scan)",
                best.order, best.methods, got.join_order, got.methods
            ),
        );
    }
    Check::pass(
        ID,
        LABEL,
        format!(
            "found {:?} with {:?} at {} milliunits — {:.1}× under the naive left-to-right plan",
            best.order,
            best.methods,
            best.cost,
            naive_cost as f64 / best.cost as f64
        ),
    )
}

/// 3. interesting_orders: the 2nd-cheapest pair plan's sorted output makes
///    the top merge free; cheapest-per-subset pruning is not enough.
pub fn check_interesting_orders() -> Check {
    const ID: &str = "interesting_orders";
    const LABEL: &str = "a sorted intermediate kept when it saves a sort later";
    let card = card_interesting();
    let best = ref_dp(&card, true);
    let flat = ref_dp(&card, false);
    if flat.cost <= best.cost {
        return Check::fail(
            ID,
            LABEL,
            "harness calibration bug: cheapest-per-subset ties the full DP — the scenario teaches nothing",
        );
    }
    let got = plan(&card);
    if let Err(e) = validate(&card, &got) {
        return Check::fail(ID, LABEL, format!("invalid plan: {e}"));
    }
    let got_cost = cost_walk(&card, &got);
    if got_cost == flat.cost {
        return Check::fail(
            ID,
            LABEL,
            format!(
                "{got_cost} milliunits is exactly the cheapest-per-subset answer: the hash join won {{0,1}} and you pruned the rest. But the 2nd-cheapest plan for {{0,1}} is a MERGE whose output arrives sorted on (table 1, col 0) — and the top join needs exactly that order, so its outer sort vanishes: {} milliunits total. A plan dominated on price is not dominated when its order is an asset",
                best.cost
            ),
        );
    }
    if got_cost != best.cost {
        return Check::fail(
            ID,
            LABEL,
            format!("your plan costs {got_cost} milliunits; the interesting-orders optimum is {} (cheapest-per-subset gets {})", best.cost, flat.cost),
        );
    }
    if got.methods.iter().any(|m| *m != JoinMethod::Merge) {
        return Check::fail(
            ID,
            LABEL,
            format!(
                "optimal cost but the methods are {:?} — the point of the scenario is merge all the way up: sorted pair output, free outer order on top",
                got.methods
            ),
        );
    }
    Check::pass(
        ID,
        LABEL,
        format!(
            "kept the sorted pair plan: {} milliunits with merges on top — {:.1}% under cheapest-per-subset's {}",
            best.cost,
            100.0 * (flat.cost - best.cost) as f64 / flat.cost as f64,
            flat.cost
        ),
    )
}

/// 4. beats_naive: 200 seeded graphs — never worse than naive left-to-right;
///    on star graphs the DP must win by the calibrated factor.
pub fn check_beats_naive() -> Check {
    const ID: &str = "beats_naive";
    const LABEL: &str = "DP plan never loses to the naive left-to-right order";
    let mut rng = Rng(0x5EED_0804);
    let mut star_min = u64::MAX; // naive/dp milli-ratio over star graphs
    let mut stars = 0usize;
    for i in 0..200usize {
        let shape = [Shape::Chain, Shape::Star, Shape::Cycle][i % 3];
        let n = 3 + rng.below(4);
        let card = gen_card(&mut rng, shape, n);
        let (naive, naive_cost) = naive_plan(&card);
        let got = plan(&card);
        if let Err(e) = validate(&card, &got) {
            return Check::fail(ID, LABEL, format!("graph {i} ({} {n} tables): invalid plan — {e}", shape.name()));
        }
        let got_cost = cost_walk(&card, &got);
        if got_cost > naive_cost {
            return Check::fail(
                ID,
                LABEL,
                format!(
                    "graph {i} ({}, {n} tables): your plan costs {got_cost} milliunits, naive left-to-right {:?} costs {naive_cost} — the DP optimizes over a space that CONTAINS the naive plan, so losing to it means the search or the pricing is broken",
                    shape.name(),
                    naive.join_order
                ),
            );
        }
        if let Shape::Star = shape {
            stars += 1;
            star_min = star_min.min(naive_cost * 1000 / got_cost.max(1));
        }
    }
    let need = STAR_FACTOR_MILLI as f64 / 1000.0;
    if star_min < STAR_FACTOR_MILLI {
        return Check::fail(
            ID,
            LABEL,
            format!(
                "on star graphs the DP must humiliate the naive order: worst improvement {:.2}× over {stars} seeded stars, required {need:.2}× — naive drags the hub in as a spilled hash build (three passes over its pages); the DP scans the hub once and probes tiny dimension hashes",
                star_min as f64 / 1000.0
            ),
        );
    }
    Check::pass(
        ID,
        LABEL,
        format!(
            "200 seeded graphs: never worse than naive; worst star-graph improvement {:.2}× (required {need:.2}×)",
            star_min as f64 / 1000.0
        ),
    )
}

/// 5. storm: 100 seeded random query graphs — exact cost match against the
///    reference DP, structural validity, honest reported total_cost.
pub fn check_storm() -> Check {
    const ID: &str = "storm";
    const LABEL: &str = "seeded random query graphs: exact cost + plan match vs reference DP";
    let mut rng = Rng(0x5EED_0805);
    for i in 0..100usize {
        let shape = [Shape::Chain, Shape::Star, Shape::Cycle][i % 3];
        let n = 3 + rng.below(4);
        let card = gen_card(&mut rng, shape, n);
        let best = ref_dp(&card, true);
        let got = plan(&card);
        if let Err(e) = validate(&card, &got) {
            return Check::fail(ID, LABEL, format!("graph {i} ({} {n} tables): invalid plan — {e}", shape.name()));
        }
        let got_cost = cost_walk(&card, &got);
        if got_cost != best.cost {
            return Check::fail(
                ID,
                LABEL,
                format!(
                    "graph {i} ({} {n} tables): your {:?} costs {got_cost} milliunits; the reference DP finds {:?} at {} — the DP keeps cheapest per (subset, interesting order); a dropped order-property or a skipped legal method surfaces exactly here",
                    shape.name(),
                    got.join_order,
                    best.order,
                    best.cost
                ),
            );
        }
        let reported = got_cost as f64 / 1000.0;
        if got.total_cost != reported {
            return Check::fail(
                ID,
                LABEL,
                format!(
                    "graph {i}: the plan reports total_cost {} but the pinned model prices it at {reported} — total_cost = cost_of(plan, card) as f64 / 1000.0, to the bit",
                    got.total_cost
                ),
            );
        }
    }
    Check::pass(
        ID,
        LABEL,
        "100 seeded graphs (chains, stars, cycles, 3–6 tables): every plan valid, every cost exact vs the reference DP",
    )
}

/// The full suite, in grading order.
pub fn self_checks() -> Vec<Check> {
    vec![
        check_cost_model(),
        check_left_deep_dp(),
        check_interesting_orders(),
        check_beats_naive(),
        check_storm(),
    ]
}

