//! hnsw — forge lab 06 (tablespace). The capstone.
//!
//! Every lab before this one graded something exact: bytes, order,
//! durability, visibility. This one grades APPROXIMATION — and the honest
//! way to grade approximation is to measure. The corpus is seeded, the
//! truth is brute force, latency is a distance-computation count on the
//! Meter, and every band below was calibrated against the reference
//! solution's measured numbers, never guessed (see the CALIBRATION block).
//!
//! ┌────────────────────────────────────────────────────────────────┐
//! │  YOU EDIT:   src/hnsw.rs       (the only file with TODO(you))  │
//! │  DO NOT EDIT this file — it is the grading harness.            │
//! └────────────────────────────────────────────────────────────────┘
//!
//! The five checks, in grading order:
//!   * graph_invariants — structural proof: caps, symmetry, reachability.
//!   * recall_band      — mean recall@10 over 50 seeded queries, in a band.
//!   * latency_win      — mean metered distances/query vs the exact scan.
//!   * planner_choice   — choose_index matches the cost verdict on a grid.
//!   * curve            — your build dominates a naive one on (recall, cost).

