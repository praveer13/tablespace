//! columnar — forge lab 09 (tablespace). The analytical engine in miniature.
//!
//! Eight labs of rows end here. This one turns the page sideways: DSM, the
//! decomposition storage model — every column stored on its own, compressed
//! block by block, with a zone map per block and an executor that works on
//! 2048-value batches behind selection masks instead of pulling one tuple
//! at a time (T7.L1/L2). Same algebra as lab 05's volcano, different
//! physics: the scan reads 2% of the bytes and never lets a tuple be born.
//!
//! ┌────────────────────────────────────────────────────────────────┐
//! │  YOU EDIT:   src/column.rs      (the only file with TODO(you)) │
//! │  DO NOT EDIT this file — it is the grading harness.            │
//! └────────────────────────────────────────────────────────────────┘
//!
//! The corpus is seeded and integer-only, so native and wasm agree to the
//! bit. A synthetic `events` table, 50,000 rows × 4 columns, in blocks of
//! BLOCK (2048) values — 24 full blocks plus a short one:
//!
//! ```text
//!   ts      i64 epoch-ms, monotone non-decreasing with ~65% repeated
//!           values — run-length heaven, narrow ascending zones
//!   status  one of 6 strings, iid-ish per row, 3% NULL — dictionary heaven
//!   region  one of 16 strings, CONSTANT within each block (physically
//!           clustered — the zone map's best case; blocks are shuffled)
//!   amount  i64, zipf-ish (small values common, large rare); ~2% NULL,
//!           blocks 5–6 are NULL-heavy (~40%), and blocks 9 and 17 are
//!           ALL NULL — the outage windows, where the sensor was down
//! ```
//!
//! The five checks, in grading order:
//!   * encode_roundtrip — decode(encode(x)) == x for every column × every
//!     encoding, byte-exact, NULLs included; a constant block is ONE run.
//!   * zone_skip        — zones match the canonical min/max/nulls exactly,
//!     and engineered predicates read exactly the blocks they must.
//!   * vectorized_ops   — scripted filter+sum queries vs the row-store
//!     reference: rows_matched and sum exact, NULL semantics included.
//!   * compression_band — total encoded size of the seeded corpus inside a
//!     band calibrated on the reference build (see CALIBRATION below).
//!   * storm            — 300 seeded mixed queries: exact answers, and
//!     blocks_read ≤ the canonical-zone ceiling on every single one.

